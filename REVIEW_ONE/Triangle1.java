package REVIEW_ONE;

public class Triangle1 {
    public static void main(String args[]){
        int n = 1;
        for (int i = 5; i>=n; i--){
            for (int j = i; j>=1; j--){
                System.out.print(j + " ");
            }
            System.out.println();
        }
    } 
    
}
